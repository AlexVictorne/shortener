// Команда exitcheck запускает статический анализатор, который проверяет
// исходный код Go на соответствие двум правилам:
//
//  1. Запрет использования встроенной функции panic в любом месте программы.
//
//  2. Запрет вызовов log.Fatal, log.Fatalf, log.Fatalln и os.Exit вне функции
//     main пакета main. В точке входа программы эти вызовы допустимы, однако
//     в прочих пакетах и функциях они нарушают принцип явной обработки ошибок
//     и лишают вызывающий код возможности корректно завершить работу.
//
// # Использование
//
//	exitcheck ./...
//
// Анализатор построен на основе golang.org/x/tools/go/analysis/singlechecker
// и совместим со стандартным интерфейсом go vet.
package main

import "golang.org/x/tools/go/analysis/singlechecker"

func main() {
	singlechecker.Main(Analyzer)
}
